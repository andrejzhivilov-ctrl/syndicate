"""
SYNDIKAT Content Factory — xAI Grok Writer for Threads & Twitter (X).
Generates viral organic threads, controversy hooks, and sniper comments.
Utilizes Grok's real-time platform awareness and native cultural tone.

Honesty contract (same rule as the rest of the syndicate):
  * no API key            -> status "unavailable", never a silent success
  * sample copy served    -> synthetic=True + an explicit warning, and only
                             when EVA_GROK_MOCK is switched on
  * successful live call  -> status "ok", synthetic=False
Every response uses the same envelope: ``status``, ``posts``, ``model``.
"""

from __future__ import annotations

import json
import os
import re
from typing import Any, Dict, List, Optional

import httpx
import structlog

from src.voice._util import read_vault_secret

logger = structlog.get_logger(__name__)

# Demo copy. It is ONLY ever returned when EVA_GROK_MOCK is enabled and is
# always tagged synthetic so it can never be mistaken for Grok's output.
MOCK_POSTS: List[str] = [
    "🔥 Most people waste 80% of their budget on bloated software.",
    "Here is the exact lean stack our holding uses to generate passive commissions without ad spend:",
    "1. AI lead scraping with automated filtering\n2. Free multi-threaded server workers\n3. Local media compositing",
    "The secret isn't more money. It's eliminating recurring SaaS fees and owning your pipeline.",
    "Bookmark this. We drop the full setup guide here: {cta} 🚀",
]

_JSON_ARRAY = re.compile(r"\[.*\]", re.DOTALL)


def _truthy(value: Optional[str]) -> bool:
    return (value or "").strip().lower() in ("1", "true", "yes", "on")


class GrokWriter:
    """Specialized AI writer utilizing xAI Grok for high-converting social copy."""

    BASE_URL = "https://api.x.ai/v1"

    def __init__(self, api_key: Optional[str] = None, model: str = "grok-beta", vault_client: Any = None):
        self._vault = vault_client
        self.api_key = api_key or ""
        self.model = model

    async def _ensure_api_key(self) -> None:
        if not self.api_key:
            self.api_key = await read_vault_secret(
                self._vault, "api-keys", "xai_api_key", env_key="XAI_API_KEY"
            ) or ""


    # ------------------------------------------------------------------ #
    @property
    def _has_key(self) -> bool:
        return bool(self.api_key) and self.api_key != "PLACEHOLDER_UPDATE_ME"

    def _unavailable(self, reason: str, posts: Optional[List[str]] = None) -> Dict[str, Any]:
        out: Dict[str, Any] = {
            "status": "unavailable",
            "posts": posts or [],
            "model": "grok-mock-local" if posts else None,
            "synthetic": bool(posts),
            "warning": reason,
        }
        if posts:
            out["warning"] += " — served DEMO copy, not generated by Grok"
        return out

    @staticmethod
    def _parse_posts(raw: str) -> List[str]:
        """Grok returns a JSON array; tolerate prose / fences around it."""
        try:
            parsed = json.loads(raw)
        except (json.JSONDecodeError, TypeError):
            match = _JSON_ARRAY.search(raw or "")
            if not match:
                return []
            try:
                parsed = json.loads(match.group(0))
            except json.JSONDecodeError:
                return []
        if isinstance(parsed, list):
            return [str(item) for item in parsed]
        if isinstance(parsed, dict):
            for key in ("posts", "thread", "tweets", "output"):
                value = parsed.get(key)
                if isinstance(value, list):
                    return [str(item) for item in value]
        return []

    async def _chat(self, system_prompt: str, user_prompt: str, temperature: float = 0.75) -> Dict[str, Any]:
        """Single Grok chat completion. Returns ``{"ok": bool, ...}``."""
        headers = {
            "Authorization": f"Bearer {self.api_key}",
            "Content-Type": "application/json",
        }
        payload = {
            "model": self.model,
            "messages": [
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_prompt},
            ],
            "temperature": temperature,
        }
        try:
            async with httpx.AsyncClient(timeout=30.0) as client:
                response = await client.post(
                    f"{self.BASE_URL}/chat/completions", headers=headers, json=payload
                )
                response.raise_for_status()
                data = response.json()
        except Exception as exc:  # noqa: BLE001
            logger.error("grok_api_request_failed", error=str(exc))
            return {"ok": False, "error": f"{type(exc).__name__}: {exc}"}

        try:
            content = data["choices"][0]["message"]["content"]
        except (KeyError, IndexError, TypeError):
            return {"ok": False, "error": "grok_unexpected_response_envelope"}
        return {"ok": True, "content": content}

    # ------------------------------------------------------------------ #
    async def generate_thread(
        self,
        topic: str,
        niche: str = "saas_affiliate",
        post_count: int = 5,
        target_cta: Optional[str] = None
    ) -> Dict[str, Any]:
        """
        Generate a multi-tweet or Threads cascade designed for organic reach.
        Avoids robotic AI fluff ('In today's fast-paced world...', 'Dive deep').

        Always returns the same envelope — the old code returned ``posts`` in
        mock mode and ``content`` (a raw string) in live mode, so callers that
        read ``posts`` silently got nothing from a real Grok call.
        """
        await self._ensure_api_key()

        cta = target_cta or "Check the link in bio"

        if not self._has_key:
            logger.info("grok_no_api_key", topic=topic)
            demo = [p.format(cta=cta) for p in MOCK_POSTS] if _truthy(os.getenv("EVA_GROK_MOCK")) else []
            return self._unavailable("XAI_API_KEY is not configured", demo)

        system_prompt = (
            "You are a top-tier viral copywriter for X and Threads. "
            "Tone: Punchy, contrarian, direct, insider knowledge, high curiosity gap. "
            "Rule 1: Hook must stop the scroll in under 1.5 seconds. "
            "Rule 2: Never use generic corporate AI words ('dive in', 'beacon', 'unleash', 'revolutionize'). "
            "Rule 3: Return a JSON array of clean strings, each representing a single post/tweet."
        )
        user_prompt = (
            f"Topic: {topic}\n"
            f"Niche: {niche}\n"
            f"Number of posts: {post_count}\n"
            f"Call to action: {cta}\n"
            f"Output exact JSON format: [\"post 1\", \"post 2\", ...]"
        )

        result = await self._chat(system_prompt, user_prompt)
        if not result["ok"]:
            return {"status": "error", "posts": [], "model": self.model,
                    "synthetic": False, "message": result["error"]}

        posts = self._parse_posts(result["content"])
        out: Dict[str, Any] = {
            "status": "ok" if posts else "error",
            "posts": posts,
            "content": result["content"],
            "model": self.model,
            "synthetic": False,
        }
        if not posts:
            out["message"] = "grok_response_not_a_json_array"
        return out

    async def generate_reply_snipe(self, target_post: str, product_angle: str) -> Dict[str, Any]:
        """Generate a high-engagement, insightful reply to a viral thread.

        Used to return one hardcoded sentence with ``status: "ok"`` regardless
        of input — a fabricated reply attributed to Grok.
        """
        await self._ensure_api_key()

        if not self._has_key:
            return {
                "status": "unavailable",
                "reply": None,
                "posts": [],
                "angle": product_angle,
                "synthetic": False,
                "warning": "XAI_API_KEY is not configured",
            }

        system_prompt = (
            "You write single, high-signal replies to viral posts. "
            "Tone: insider, concrete, never sycophantic. One short paragraph, "
            "no hashtags, no emoji, and never repeat the original post."
        )
        user_prompt = (
            f"Original post:\n{target_post}\n\n"
            f"Angle to land: {product_angle}\n"
            "Write the reply only."
        )

        result = await self._chat(system_prompt, user_prompt, temperature=0.8)
        if not result["ok"]:
            return {"status": "error", "reply": None, "posts": [], "angle": product_angle,
                    "synthetic": False, "message": result["error"]}

        reply = (result["content"] or "").strip()
        return {
            "status": "ok" if reply else "error",
            "reply": reply or None,
            "posts": [reply] if reply else [],
            "angle": product_angle,
            "model": self.model,
            "synthetic": False,
        }
